-- 9. CREATE VIEWS FOR EASY ACCESS
-- ============================================================

-- View for documents with office names
CREATE OR REPLACE VIEW public.documents_view AS
SELECT 
  d.id,
  d.date,
  d.office_id,
  o.name AS office_name,
  d.time,
  d.description,
  d.received,
  d.created_at,
  d.updated_at
FROM public.documents d
LEFT JOIN public.offices o ON d.office_id = o.id
ORDER BY d.date DESC, d.time DESC;

GRANT SELECT ON public.documents_view TO anon, authenticated;

-- View for monitoring summary
CREATE OR REPLACE VIEW public.monitoring_summary AS
SELECT 
  description,
  COUNT(*) AS total_records,
  MIN(date) AS first_date,
  MAX(date) AS last_date,
  COUNT(DISTINCT date) AS total_days
FROM public.monitoring
GROUP BY description
ORDER BY description ASC;

GRANT SELECT ON public.monitoring_summary TO anon, authenticated;

-- View for daily monitoring counts
CREATE OR REPLACE VIEW public.monitoring_daily AS
SELECT 
  description,
  date,
  COUNT(*) AS daily_count,
  STRING_AGG(followup, ' | ' ORDER BY id) AS followups
FROM public.monitoring
GROUP BY description, date
ORDER BY date DESC, description ASC;

GRANT SELECT ON public.monitoring_daily TO anon, authenticated;

