-- 10. HELPER FUNCTIONS
-- ============================================================

-- Function to get documents by description
CREATE OR REPLACE FUNCTION public.get_documents_by_description(
  search_description TEXT
)
RETURNS SETOF public.documents_view
LANGUAGE sql
AS $$
  SELECT * FROM public.documents_view
  WHERE description ILIKE '%' || search_description || '%'
  ORDER BY date DESC;
$$;

-- Function to get monitoring by description
CREATE OR REPLACE FUNCTION public.get_monitoring_by_description(
  search_description TEXT
)
RETURNS SETOF public.monitoring
LANGUAGE sql
AS $$
  SELECT * FROM public.monitoring
  WHERE description = search_description
  ORDER BY date DESC;
$$;

-- Function to get monitoring by date range
CREATE OR REPLACE FUNCTION public.get_monitoring_by_date_range(
  start_date DATE,
  end_date DATE
)
RETURNS SETOF public.monitoring
LANGUAGE sql
AS $$
  SELECT * FROM public.monitoring
  WHERE date BETWEEN start_date AND end_date
  ORDER BY date DESC, description ASC;
$$;

-- Function to get monitoring by description and date range
CREATE OR REPLACE FUNCTION public.get_monitoring_by_description_date(
  search_description TEXT,
  start_date DATE,
  end_date DATE
)
RETURNS SETOF public.monitoring
LANGUAGE sql
AS $$
  SELECT * FROM public.monitoring
  WHERE description = search_description
    AND date BETWEEN start_date AND end_date
  ORDER BY date DESC;
$$;

