-- 1. CREATE THE OFFICES TABLE (referenced by documents)
-- ============================================================

CREATE TABLE IF NOT EXISTS public.offices (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name         TEXT NOT NULL UNIQUE,
  created_at   TIMESTAMP WITH TIME ZONE DEFAULT NOW() NOT NULL,
  updated_at   TIMESTAMP WITH TIME ZONE DEFAULT NOW() NOT NULL
);

-- Add index for offices
CREATE INDEX IF NOT EXISTS idx_offices_name ON public.offices (name);

-- ============================================================
-- 2. CREATE THE DOCUMENTS TABLE (from your document receive system)
-- ============================================================

CREATE TABLE IF NOT EXISTS public.documents (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  date         DATE NOT NULL,
  office_id    BIGINT NOT NULL REFERENCES public.offices(id) ON DELETE CASCADE,
  time         TIME NOT NULL,
  description  TEXT NOT NULL,
  received     TEXT DEFAULT '',
  created_at   TIMESTAMP WITH TIME ZONE DEFAULT NOW() NOT NULL,
  updated_at   TIMESTAMP WITH TIME ZONE DEFAULT NOW() NOT NULL
);

-- Add indexes for documents
CREATE INDEX IF NOT EXISTS idx_documents_date ON public.documents (date);
CREATE INDEX IF NOT EXISTS idx_documents_office_id ON public.documents (office_id);
CREATE INDEX IF NOT EXISTS idx_documents_description ON public.documents (description);

-- ============================================================
-- 3. CREATE THE MONITORING TABLE (for daily monitoring)
-- ============================================================

