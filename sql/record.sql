-- 9. CREATE VIEW FOR EASY ACCESS
-- ============================================================

CREATE OR REPLACE VIEW public.documents_view AS
SELECT 
  d.id,
  d.date,
  d.office_id,
  o.name AS office_name,
  d.time,
  d.description,
  d.received,
  d.created_at,
  d.updated_at
FROM public.documents d
LEFT JOIN public.offices o ON d.office_id = o.id
ORDER BY d.date DESC, d.time DESC;

-- Grant access to the view
GRANT SELECT ON public.documents_view TO anon, authenticated;

