-- Drop tables in reverse order to avoid dependency issues
DROP TABLE IF EXISTS public.documents CASCADE;
DROP TABLE IF EXISTS public.offices CASCADE;

-- Create offices table
CREATE TABLE public.offices (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name         TEXT NOT NULL UNIQUE,
  created_at   TIMESTAMP WITH TIME ZONE DEFAULT NOW() NOT NULL,
  updated_at   TIMESTAMP WITH TIME ZONE DEFAULT NOW() NOT NULL
);

-- Add indexes for offices
CREATE INDEX IF NOT EXISTS idx_offices_name ON public.offices (name);

-- ============================================================
-- 2. CREATE THE DOCUMENTS TABLE (references offices)
-- ============================================================

CREATE TABLE public.documents (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  date         DATE NOT NULL,
  office_id    BIGINT NOT NULL REFERENCES public.offices(id) ON DELETE CASCADE,
  time         TIME NOT NULL,
  description  TEXT NOT NULL,
  received     TEXT DEFAULT '',
  created_at   TIMESTAMP WITH TIME ZONE DEFAULT NOW() NOT NULL,
  updated_at   TIMESTAMP WITH TIME ZONE DEFAULT NOW() NOT NULL
);

-- Add indexes for faster queries
CREATE INDEX IF NOT EXISTS idx_documents_date ON public.documents (date);
CREATE INDEX IF NOT EXISTS idx_documents_office_id ON public.documents (office_id);
CREATE INDEX IF NOT EXISTS idx_documents_received ON public.documents (received);

