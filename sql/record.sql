-- 11. HELPER FUNCTIONS (OPTIONAL)
-- ============================================================

-- Function to get documents by date range
CREATE OR REPLACE FUNCTION public.get_documents_by_date_range(
  start_date DATE,
  end_date DATE
)
RETURNS SETOF public.documents_view
LANGUAGE sql
AS $$
  SELECT * FROM public.documents_view
  WHERE date BETWEEN start_date AND end_date
  ORDER BY date DESC, time DESC;
$$;

-- Function to get documents by office
CREATE OR REPLACE FUNCTION public.get_documents_by_office(
  office_id BIGINT
)
RETURNS SETOF public.documents_view
LANGUAGE sql
AS $$
  SELECT * FROM public.documents_view
  WHERE office_id = $1
  ORDER BY date DESC, time DESC;
$$;

-- Function to get signed documents
CREATE OR REPLACE FUNCTION public.get_signed_documents()
RETURNS SETOF public.documents_view
LANGUAGE sql
AS $$
  SELECT * FROM public.documents_view
  WHERE received IS NOT NULL AND received != ''
  ORDER BY date DESC, time DESC;
$$;

-- Function to get unsigned documents
CREATE OR REPLACE FUNCTION public.get_unsigned_documents()
RETURNS SETOF public.documents_view
LANGUAGE sql
AS $$
  SELECT * FROM public.documents_view
  WHERE received IS NULL OR received = ''
  ORDER BY date DESC, time DESC;
$$;

